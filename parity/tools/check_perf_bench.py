#!/usr/bin/env python3
"""Run paired Rust/Python performance bodies and publish the local baseline."""
from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def run(cmd: list[str], *, capture: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        cmd,
        cwd=ROOT,
        text=True,
        encoding="utf-8",
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        check=False,
    )


def seconds(value: float) -> str:
    return f"{value:.3f}s"


def ratio(rust: float, python: float) -> str:
    if python <= 0:
        return "n/a"
    return f"{rust / python:.2f}x"


def markdown(reports: dict[str, dict], elapsed: dict[str, float], corpus: str) -> str:
    rust = reports["rust"]
    python = reports["python"]
    rows = [
        ("Cold import", "first_seconds", "s"),
        ("Unchanged re-import", "second_seconds", "s"),
        ("Embed median (warm)", "embed_median_seconds", "s"),
        ("Search median (warm)", "search_median_seconds", "s"),
        ("Peak RSS", "peak_rss_kb", "KiB"),
        ("Full process wall time", None, "s"),
    ]
    lines = [
        "# Performance baseline",
        "",
        "Generated by `parity/tools/check_perf_bench.py` on the local CUDA",
        "workstation. Numbers are regression evidence, not a cross-machine SLA.",
        "",
        f"- corpus: `{corpus}`",
        f"- platform: `{platform.platform()}`",
        f"- Python: `{platform.python_version()}`",
        f"- oracle: `python-oracle-0.15.0` via `parity/tools/oracle.py`",
        "",
        "| Metric | Rust | Python 0.15 | Rust / Python |",
        "| --- | ---: | ---: | ---: |",
    ]
    for label, key, unit in rows:
        if key is None:
            r, p = elapsed["rust"], elapsed["python"]
            formatted_r, formatted_p = seconds(r), seconds(p)
        elif unit == "s":
            r, p = float(rust[key]), float(python[key])
            formatted_r, formatted_p = seconds(r), seconds(p)
        else:
            r, p = float(rust[key]), float(python[key])
            formatted_r, formatted_p = f"{int(r)}", f"{int(p)}"
        lines.append(f"| {label} | {formatted_r} | {formatted_p} | {ratio(r, p)} |")

    lines.extend([
        "",
        "Additional counters:",
        "",
        f"- Rust concepts: {rust['concepts']}; Python concepts: {python['concepts']}",
        f"- Rust search results: {rust['search_results']}; "
        f"Python search results: {python['search_results']}",
        f"- Rust delta queue: {rust['second_queued']}; "
        f"Python delta queue: {python['second_queued']}",
        f"- Rust search-with-vector samples: {rust.get('search_vec_samples_seconds')}",
        f"- Rust embed samples: {rust['embed_samples_seconds']}",
        f"- Python embed samples: {python['embed_samples_seconds']}",
        f"- Rust search samples: {rust['search_samples_seconds']}",
        f"- Python search samples: {python['search_samples_seconds']}",
        "",
        "## Methodology",
        "",
        "Both runners import `parity/corpus/filters` into a fresh temporary v10 DB",
        "with the real `google/embeddinggemma-2` model on CUDA, chunk size 32 and",
        "overlap 4. Rust is built with `--release`; Python runs the oracle venv.",
        "One warm search precedes five timed `search` calls. Peak RSS",
        "is sampled inside each process; process wall time includes interpreter or",
        "binary startup. Run this only on the manual GPU release gate.",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default="parity/corpus/filters")
    ap.add_argument("--oracle-python", default="parity/.venv-oracle/Scripts/python.exe")
    ap.add_argument("--report", default="docs/performance-baseline.md")
    ap.add_argument("--max-first-seconds", type=float, default=60.0)
    ap.add_argument("--max-second-seconds", type=float, default=5.0)
    ap.add_argument("--max-search-seconds", type=float, default=10.0)
    args = ap.parse_args()

    build = run(["cargo", "build", "-q", "--release", "-p", "okfgraph", "--example", "perf_bench"])
    if build.returncode:
        print(build.stderr[-2000:])
        raise SystemExit("cannot build perf_bench")

    suffix = ".exe" if os.name == "nt" else ""
    rust_exe = ROOT / "target/release/examples" / f"perf_bench{suffix}"
    commands = {
        "rust": [str(rust_exe), args.corpus],
        "python": [
            str(ROOT / args.oracle_python),
            "parity/tools/python_bench.py",
            args.corpus,
        ],
    }

    reports: dict[str, dict] = {}
    elapsed: dict[str, float] = {}
    for name, cmd in commands.items():
        started = time.perf_counter()
        proc = run(cmd)
        elapsed[name] = time.perf_counter() - started
        if proc.returncode:
            print(proc.stderr[-4000:])
            raise SystemExit(f"{name} perf body failed ({proc.returncode})")
        try:
            reports[name] = json.loads(proc.stdout)
        except ValueError as exc:
            raise SystemExit(f"{name} perf body emitted non-JSON: {proc.stdout[:400]}") from exc

    failures = []
    rust = reports["rust"]
    python = reports["python"]
    for name, report in reports.items():
        if report["concepts"] < 6:
            failures.append(f"{name}: only {report['concepts']} concepts")
        if report["search_results"] < 1:
            failures.append(f"{name}: no search results")
        if report["second_queued"] != 0:
            failures.append(f"{name}: unchanged re-import queued files")
        if report["first_seconds"] > args.max_first_seconds:
            failures.append(f"{name}: cold import too slow")
        if report["second_seconds"] > args.max_second_seconds:
            failures.append(f"{name}: delta no-op too slow")
        if report["embed_median_seconds"] > args.max_search_seconds:
            failures.append(f"{name}: embed too slow")
        if report["search_median_seconds"] > args.max_search_seconds:
            failures.append(f"{name}: search too slow")
    if rust["concepts"] != python["concepts"]:
        failures.append("concept counts differ")
    if rust["search_results"] != python["search_results"]:
        failures.append("search result counts differ")

    out = ROOT / "parity/out/perf-bench.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        json.dumps({"reports": reports, "elapsed": elapsed}, indent=2),
        encoding="utf-8",
    )
    report_path = ROOT / args.report
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(markdown(reports, elapsed, args.corpus), encoding="utf-8")

    print(
        "import: "
        f"rust {seconds(rust['first_seconds'])} / python {seconds(python['first_seconds'])}; "
        "search median: "
        f"rust {seconds(rust['search_median_seconds'])} / "
        f"python {seconds(python['search_median_seconds'])}"
    )
    print(f"report: {report_path.relative_to(ROOT)}")
    if failures:
        for failure in failures:
            print("FAIL:", failure)
        return 1
    print("OK: paired performance baseline recorded")
    return 0


if __name__ == "__main__":
    sys.exit(main())
