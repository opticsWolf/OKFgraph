#!/usr/bin/env python3
"""Regenerate src/settings/table.rs from the frozen Python settings oracle."""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location(
    "oracle_settings", ROOT / "okfgraph" / "settings.py"
)
module = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(module)


def rust_str(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def default_expr(value: object) -> str:
    if value is None:
        return "DefaultValue::Null"
    if isinstance(value, bool):
        return f"DefaultValue::Bool({str(value).lower()})"
    if isinstance(value, int):
        return f"DefaultValue::Int({value})"
    if isinstance(value, float):
        return f"DefaultValue::Float({value!r})"
    if isinstance(value, list):
        return "DefaultValue::List"
    return f"DefaultValue::Str({rust_str(str(value))})"


def opt_str(value: object) -> str:
    return "None" if value is None else f"Some({rust_str(str(value))})"


def main() -> None:
    lines = [
        "// @generated by parity/tools/gen_settings.py from python-oracle-0.15.0",
        "// Do not edit by hand; regenerate when the oracle table changes.\n",
        "pub const SETTINGS: &[SettingDef] = &[",
    ]
    for row in module.SETTINGS:
        choices = ", ".join(rust_str(c) for c in row.choices)
        lines.extend(
            [
                "    SettingDef {",
                f"        name: {rust_str(row.name)},",
                f"        kind: SettingKind::{ {'str': 'Str', 'int': 'Int', 'float': 'Float', 'bool': 'Bool', 'csv': 'Csv'}[row.kind] },",
                f"        default: {default_expr(row.default)},",
                f"        section: {rust_str(row.section)},",
                f"        help: {rust_str(row.help)},",
                f"        choices: &[{choices}],",
                f"        cli: {str(row.cli).lower()},",
                f"        mcp: {str(row.mcp).lower()},",
                f"        flag: {opt_str(row.flag)},",
                f"        dest: {opt_str(row.dest)},",
                f"        invert: {str(row.invert).lower()},",
                f"        required_mcp: {str(row.required_mcp).lower()},",
                "    },",
            ]
        )
    lines.append("];\n")
    out = ROOT / "src" / "settings" / "table.rs"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(module.SETTINGS)} settings)")

    py = [
        '"""Public settings constants and read-only table for the facade."""',
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Any, Optional, Tuple",
        "",
        f"DEFAULT_MODEL_ID = {module.DEFAULT_MODEL_ID!r}",
        f"DEFAULT_RERANK_MODEL_ID = {module.DEFAULT_RERANK_MODEL_ID!r}",
        f"GRAPH_HOME = {module.GRAPH_HOME!r}",
        f"DEFAULT_DB_PATH = {module.DEFAULT_DB_PATH!r}",
        f"LEGACY_DB_PATH = {module.LEGACY_DB_PATH!r}",
        f"DEVICES = {tuple(module.DEVICES)!r}",
        f"PRECISIONS = {tuple(module.PRECISIONS)!r}",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Setting:",
        "    name: str",
        "    kind: str",
        "    default: Any",
        "    section: str",
        "    help: str",
        "    choices: Tuple[str, ...] = ()",
        "    cli: bool = True",
        "    mcp: bool = True",
        "    flag: Optional[str] = None",
        "    dest: Optional[str] = None",
        "    invert: bool = False",
        "    required_mcp: bool = False",
        "",
        "",
        "SETTINGS = (",
    ]
    for row in module.SETTINGS:
        py.append(
            f"    Setting({row.name!r}, {row.kind!r}, {row.default!r}, "
            f"{row.section!r}, {row.help!r}, {tuple(row.choices)!r}, "
            f"{row.cli!r}, {row.mcp!r}, {row.flag!r}, {row.dest!r}, "
            f"{row.invert!r}, {row.required_mcp!r}),"
        )
    py.extend([
        ")",
        "",
        "",
        "def env_name(name: str) -> str:",
        '    return f"OKFGRAPH_{name.upper()}"',
        "",
        "",
        "def flag_name(name: str) -> str:",
        '    return "--" + name.replace("_", "-")',
        "",
        "MCP_REQUIRED = tuple(row.name for row in SETTINGS if row.required_mcp)",
        "",
    ])
    py_out = ROOT / "python" / "okfgraph" / "settings.py"
    py_out.write_text("\n".join(py), encoding="utf-8")
    print(f"wrote {py_out}")


if __name__ == "__main__":
    main()
